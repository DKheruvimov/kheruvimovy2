        file_put_contents($lockFile, "Installed on " . date('Y-m-d H:i:s') . "\n");
        
        // Proceed to Step 3 - Success Screen!
        $step = 3;
    } catch (Exception $e) {
        if (isset($pdo) && $pdo->inTransaction()) {
            $pdo->rollBack();
        }
        $errorMsg = "Ошибка при установке системы: " . $e->getMessage();
    }
}
