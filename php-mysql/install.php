            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            PDO::ATTR_EMULATE_PREPARES   => false,
            PDO::MYSQL_ATTR_INIT_COMMAND => "SET NAMES utf8mb4 COLLATE utf8mb4_unicode_ci"
        ];
        
        $pdo = new PDO($dsnWithoutDb, $db_user, $db_pass, $options);
        
        // Step B: Ensure the database exists or create it
        // We will execute a query to create the database if permitted
        $pdo->exec(sprintf("CREATE DATABASE IF NOT EXISTS `%s` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci", $db_name));
        
        // Connect to the specific database
        $pdo->exec(sprintf("USE `%s`", $db_name));
        
        // Step C: Import Schema SQL
        if (file_exists($schemaFile)) {
            $sqlContent = file_get_contents($schemaFile);
            
            // Clean SQL commands to run cleanly one by one (multi-queries in single execute can have issues depending on PDO drivers)
            // Remove MySQL Comments
            $sqlContent = preg_replace('/^\s*--.*$/m', '', $sqlContent);
            $sqlContent = preg_replace('/^\s*#.*$/m', '', $sqlContent);
            
            // Split database commands by semicolon
            $queries = explode(';', $sqlContent);
            
            // Execute each SQL command individually inside a transaction
            $pdo->beginTransaction();
            foreach ($queries as $query) {
                $query = trim($query);
                if (!empty($query)) {
                    // Skip general DB-level commands in case they enforce specific local server state
                    if (stripos($query, 'CREATE DATABASE') === 0 || stripos($query, 'USE ') === 0) {
                        continue;
                    }
                    $pdo->exec($query);
                }
            }
            $pdo->commit();
        } else {
            throw new Exception("Файл schema.sql не найден для выполнения импорта таблиц.");
        }
        
